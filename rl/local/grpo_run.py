"""Single-RTX-4090 math GRPO: in-process vLLM rollout + FSDP2 learner, time-shared.

One process, run under scripts/with_gpu.sh. vLLM (V1, uni executor, a small
gpu-memory share) and the FSDP2 learner (rl.learner.train) live on one GPU and
take turns: rollout -> reward -> learner step -> weight sync into vLLM. Weights
go learner -> vLLM in memory (model.load_weights), never through disk.

Schedules (same trained-sample budget):
  sync  (k=0): train on the batch just generated by the current policy;
  async (k=1): rollout runs one batch ahead, so each step trains on a batch
               generated one policy version earlier. On one serial GPU this
               changes data staleness only; it cannot overlap compute.

Held-out pass@1 (GSM8K test subset, MATH-500 subset) is measured before and
after training with the same fixed sampling seeds. Reward is the project's
bounded math verifier (rl.verifiers.math) on the last \\boxed{} answer.
--reward eos also scores a completion 0 when it hit max tokens without EOS
(the "right box, then run on" exploit the first sync k=0 run learned).

GPU-idle share per step = (wall - rollout - learn - sync) / wall: time the
GPU waits on CPU work (reward grading, batching). Other tenants' GPU use is
not visible to this process and is not counted.
"""

import argparse
import gzip
import json
import math
import os
import re
import sys
import time
from collections import deque
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

INSTRUCTION = "Please reason step by step, and put your final answer within \\boxed{}."
EVAL_TEMPERATURE, EVAL_TOP_P = 0.6, 0.95


class StaleQueue:
    """Hold k generated batches before training: k=0 sync, k=1 one-step async."""

    def __init__(self, k):
        self.k, self.items = k, deque()

    def push(self, batch):
        self.items.append(batch)
        return self.items.popleft() if len(self.items) > self.k else None

    def pending(self):
        return len(self.items)


def prompt_messages(question):
    return [{"role": "user", "content": f"{question}\n{INSTRUCTION}"}]


def _boxes(text):
    out = []
    for m in re.finditer(r"\\boxed\s*\{", text):
        depth, start = 1, m.end()
        for end in range(start, len(text)):
            depth += (text[end] == "{") - (text[end] == "}")
            if depth == 0:
                out.append(text[start:end].strip())
                break
    return out


def math_flags(text, truncated):
    """Reward-hacking/format signals for math: hedged multi-answer boxes, no box."""
    flags = []
    boxes = _boxes(text)
    if len(set(boxes)) > 1:
        flags.append("multiple_boxed_answers")
    if not boxes:
        flags.append("no_boxed_answer")
    if truncated:
        flags.append("truncated")
    return flags


REWARD_MODES = ("none", "eos")


def shaped_reward(correct, finish_reason, mode):
    """1/0 math reward; mode "eos" gives 0 to completions truncated at max tokens."""
    if mode not in REWARD_MODES:
        raise ValueError(f"unknown reward mode {mode!r}")
    if mode == "eos" and finish_reason == "length":
        return 0.0
    return 1.0 if correct else 0.0


def idle_share(phases, wall_s):
    busy = phases["rollout_s"] + phases["learn_s"] + phases["sync_s"]
    return max(0.0, wall_s - busy) / wall_s


def eval_summary(outcomes):
    from rl.eval.pass_at_1 import pass_at_1

    per = [pass_at_1(len(v), sum(v)) for v in outcomes.values()]
    mean = sum(per) / len(per)
    var = sum((p - mean) ** 2 for p in per) / max(1, len(per) - 1)
    return {
        "problems": len(per),
        "samples_per_problem": len(next(iter(outcomes.values()))),
        "pass_at_1": mean,
        "stderr": math.sqrt(var / len(per)),
    }


def grade(pool, texts, answers):
    from rl.verifiers.math import verify_math

    verdicts = list(pool.map(lambda pair: verify_math(*pair), zip(texts, answers, strict=True)))
    return [v.correct for v in verdicts], [v.reason for v in verdicts]


def run_eval(llm, tokenizer, sets, n, max_tokens, pool, out_path):
    from vllm import SamplingParams

    results = {}
    with gzip.open(out_path, "wt") as log:
        for name, rows in sets.items():
            prompts = [tokenizer.apply_chat_template(prompt_messages(r["question"]), tokenize=False, add_generation_prompt=True) for r in rows]
            params = [
                SamplingParams(n=n, temperature=EVAL_TEMPERATURE, top_p=EVAL_TOP_P, max_tokens=max_tokens, seed=10_000 + i)
                for i in range(len(rows))
            ]
            outputs = llm.generate(prompts, params, use_tqdm=False)
            texts = [c.text for o in outputs for c in sorted(o.outputs, key=lambda c: c.index)]
            answers = [r["answer"] for r in rows for _ in range(n)]
            correct, _ = grade(pool, texts, answers)
            outcomes = {r["id"]: correct[i * n : (i + 1) * n] for i, r in enumerate(rows)}
            log.writelines(
                json.dumps({"set": name, "id": r["id"], "i": c.index, "text": c.text, "finish": c.finish_reason}) + "\n"
                for r, o in zip(rows, outputs, strict=True)
                for c in sorted(o.outputs, key=lambda c: c.index)
            )
            summary = eval_summary(outcomes)
            summary["truncated"] = sum(c.finish_reason == "length" for o in outputs for c in o.outputs)
            summary["per_problem_correct"] = {k: sum(v) for k, v in outcomes.items()}
            results[name] = summary
    return results


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", type=Path, required=True)
    p.add_argument("--model", required=True, help="local base snapshot path")
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--staleness", type=int, choices=(0, 1), default=1)
    p.add_argument("--kl", type=float, default=0.001)
    p.add_argument("--group", type=int, default=8)
    p.add_argument("--prompts-per-step", type=int, default=8)
    p.add_argument("--steps", type=int, default=100)
    p.add_argument("--lr", type=float, default=3e-6)
    p.add_argument("--clip", type=float, default=0.2)
    p.add_argument("--max-new-tokens", type=int, default=384)
    p.add_argument("--eval-n", type=int, default=4)
    p.add_argument("--eval-max-tokens", type=int, default=512)
    # Microbatch 8 OOMed on the shared 24 GB card (8 x seq x 152k-vocab logits); the
    # loss is token-weighted across microbatches, so the update does not depend on it.
    p.add_argument("--microbatch", type=int, default=2)
    p.add_argument("--vllm-mem", type=float, default=0.15)
    p.add_argument("--seed", type=int, default=17)
    p.add_argument("--reward", choices=REWARD_MODES, default="none")
    args = p.parse_args(argv)

    from rl.learner.runtime import configure_runtime

    configure_runtime()
    os.environ.update({"VLLM_USE_V1": "1", "VLLM_ENABLE_V1_MULTIPROCESSING": "0", "VLLM_NO_USAGE_STATS": "1", "DO_NOT_TRACK": "1"})
    import torch
    from vllm import LLM, SamplingParams

    from rl.learner.train import LearnerConfig, RolloutGroup, load_fsdp2_learner
    from rl.rollout.sampler import Prompt, SamplingConfig, samples_from_outputs

    args.output.mkdir(parents=True, exist_ok=False)
    data = json.loads(args.data.read_text())
    started = time.monotonic()
    summary = {"args": {k: str(v) for k, v in vars(args).items()}, "data_sha256": data["sha256"]}
    llm = LLM(
        model=args.model, dtype="bfloat16", seed=args.seed, gpu_memory_utilization=args.vllm_mem,
        max_model_len=1024, enforce_eager=True, distributed_executor_backend="uni",
        enable_prefix_caching=True, max_num_seqs=128, generation_config="vllm",
        logprobs_mode="raw_logprobs", max_logprobs=1,
    )  # fmt: skip
    tokenizer = llm.get_tokenizer()
    pool = ThreadPoolExecutor(16)
    sets = {"gsm8k": data["gsm8k_eval"], "math500": data["math500_eval"]}
    t = time.monotonic()
    summary["before"] = run_eval(llm, tokenizer, sets, args.eval_n, args.eval_max_tokens, pool, args.output / "eval-before.jsonl.gz")
    summary["eval_before_s"] = time.monotonic() - t
    print(json.dumps({"before": {k: v["pass_at_1"] for k, v in summary["before"].items()}}), flush=True)

    config = LearnerConfig(
        group_size=args.group, microbatch_size=args.microbatch, max_length=1024,
        max_staleness=args.staleness, clip_eps=args.clip, kl_coef=args.kl, scale_by_std=True,
    )  # fmt: skip
    learner = load_fsdp2_learner(args.model, config, learning_rate=args.lr)
    sampling = SamplingConfig(seed=args.seed, temperature=1.0, top_p=1.0, top_k=-1, max_tokens=args.max_new_tokens, max_model_len=1024)
    train = data["train"]
    answers = {r["id"]: r["answer"] for r in train}
    queue, cursor, vllm_version = StaleQueue(args.staleness), 0, 0
    totals = {"generated": 0, "trained": 0, "dropped_stale": 0, "flags": {}}
    steps_log = open(args.output / "steps.jsonl", "w")  # noqa: SIM115 - closed at the end
    step = generation = 0
    while step < args.steps:
        wall0 = time.monotonic()
        rows = [train[(cursor + i) % len(train)] for i in range(args.prompts_per_step)]
        cursor += args.prompts_per_step
        prompts = [Prompt(r["id"], tokenizer.apply_chat_template(prompt_messages(r["question"]), tokenize=False, add_generation_prompt=True)) for r in rows]
        params = [
            SamplingParams(n=args.group, temperature=1.0, top_p=1.0, top_k=-1, max_tokens=args.max_new_tokens, logprobs=0,
                           seed=(args.seed * 1_000_003 + generation * 1009 + i) % 2**31)
            for i in range(len(prompts))
        ]  # fmt: skip
        t = time.monotonic()
        outputs = llm.generate([pr.text for pr in prompts], params, use_tqdm=False)
        rollout_s = time.monotonic() - t
        samples = samples_from_outputs(prompts, outputs, args.group, vllm_version)
        finish = [c.finish_reason for o in outputs for c in sorted(o.outputs, key=lambda c: c.index)]
        t = time.monotonic()
        correct, _ = grade(pool, [s.text for s in samples], [answers[s.prompt_id] for s in samples])
        reward_s = time.monotonic() - t
        flags = {}
        for s, f in zip(samples, finish, strict=True):
            for flag in math_flags(s.text, f == "length"):
                flags[flag] = flags.get(flag, 0) + 1
        groups = []
        for gi, pr in enumerate(prompts):
            part = samples[gi * args.group : (gi + 1) * args.group]
            sl = slice(gi * args.group, (gi + 1) * args.group)
            rewards = tuple(shaped_reward(c, f, args.reward) for c, f in zip(correct[sl], finish[sl], strict=True))
            groups.append(RolloutGroup(f"g{generation}", f"g{generation}/{gi}", pr, tuple(part), rewards, sampling))
        totals["generated"] += len(samples)
        generation += 1
        shaped = sum(sum(g.rewards) for g in groups) / len(samples)
        batch = queue.push({"groups": groups, "version": vllm_version, "reward": sum(correct) / len(correct),
                            "shaped_reward": shaped, "flags": flags,
                            "len": sum(len(s.token_ids) for s in samples) / len(samples)})  # fmt: skip
        if batch is None:
            continue  # async warm-up generation; nothing to train yet
        t = time.monotonic()
        metrics = learner.step(batch["groups"])
        torch.cuda.synchronize()
        learn_s = time.monotonic() - t
        t = time.monotonic()
        with torch.no_grad():
            weights = [(n, p.full_tensor().to(torch.bfloat16)) for n, p in learner.policy.named_parameters()]
        llm.apply_model(lambda model, w=weights: model.load_weights(w))
        llm.reset_prefix_cache()
        torch.cuda.synchronize()
        del weights
        vllm_version = learner.policy_version
        sync_s = time.monotonic() - t
        wall = time.monotonic() - wall0
        phases = {"rollout_s": rollout_s, "learn_s": learn_s, "sync_s": sync_s}
        totals["trained"] += metrics["accepted_samples"]
        totals["dropped_stale"] += metrics["dropped_stale"]
        for k, v in batch["flags"].items():
            totals["flags"][k] = totals["flags"].get(k, 0) + v
        entry = {
            "step": step, "trained_version": batch["version"], "policy_version": metrics["policy_version"],
            "reward": batch["reward"], "shaped_reward": batch["shaped_reward"], "mean_completion_tokens": batch["len"], "flags": batch["flags"],
            **phases, "reward_s": reward_s, "wall_s": wall, "gpu_idle_share": idle_share(phases, wall),
            **{k: metrics[k] for k in ("loss", "dropped_stale", "accepted_samples", "effective_tokens")},
        }  # fmt: skip
        steps_log.write(json.dumps(entry) + "\n")
        steps_log.flush()
        if step % 10 == 0:
            print(json.dumps({k: entry[k] for k in ("step", "reward", "loss", "wall_s", "sync_s")}), flush=True)
        step += 1
    steps_log.close()
    t = time.monotonic()
    summary["after"] = run_eval(llm, tokenizer, sets, args.eval_n, args.eval_max_tokens, pool, args.output / "eval-after.jsonl.gz")
    summary["eval_after_s"] = time.monotonic() - t
    summary["totals"] = totals
    summary["peak_cuda_allocated_bytes"] = torch.cuda.max_memory_allocated()
    summary["wall_s"] = time.monotonic() - started
    (args.output / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    print(json.dumps({"after": {k: v["pass_at_1"] for k, v in summary["after"].items()}}), flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
